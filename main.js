  async applyAnnotationHistory(op) {
    if (op.type === "remove") {
      if (!this.data.some((item) => item.id === op.annotation.id))
        return;
      await this.removeAnnotation(op.annotation.id, false);
      return;
    }
    if (this.data.some((item) => item.id === op.annotation.id))
      return;
    await this.addAnnotation(op.annotation);
  }
